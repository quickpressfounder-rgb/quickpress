const STORAGE_KEY = "quickpress_lang_v1";
const FIRST_TIME_KEY = "quickpress_lang_chosen_v1";

interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  isLanguageModalOpen: boolean;
  openLanguageModal: () => void;
  closeLanguageModal: () => void;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "en",
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
  isLanguageModalOpen: false,
  openLanguageModal: () => {},
  closeLanguageModal: () => {},
});

const originalTextMap = new WeakMap<Node, string>();

function translateText(text: string, lang: LanguageCode): string {
  if (lang === "en" || !text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  const dict = TRANSLATIONS[lang];
  if (!dict) return text;

  // Direct exact match
  if (dict[trimmed]) {
    const leading = text.match(/^\s*/)?.[0] || "";
    const trailing = text.match(/\s*$/)?.[0] || "";
    return leading + dict[trimmed] + trailing;
  }

  // Regex patterns
  const viewAllMatch = trimmed.match(/^View all\s*\((\d+)\)$/i);
  if (viewAllMatch) {
    const num = viewAllMatch[1];
    const base = dict["View all"] || "View all";
    return `${base} (${num})`;
  }

  const approvalsMatch = trimmed.match(/^Approvals\s*\((\d+)\)$/i);
  if (approvalsMatch) {
    const num = approvalsMatch[1];
    const base = dict["Approvals"] || "Approvals";
    return `${base} (${num})`;
  }

  const addOfferMatch = trimmed.match(/^Add Offer\s*\((\d+)\)$/i);
  if (addOfferMatch) {
    const num = addOfferMatch[1];
    const base = dict["Add Offer"] || "Add Offer";
    return `${base} (${num})`;
  }

  // Substring replacement ONLY for pure human phrases (no dot keys)
  let result = text;
  for (const [phraseKey, transVal] of Object.entries(dict)) {
    if (!phraseKey.includes(".") && phraseKey.length > 3 && result.includes(phraseKey)) {
      result = result.replaceAll(phraseKey, transVal);
    }
  }

  return result;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLangState] = useState<LanguageCode>("en");
  const [isLanguageModalOpen, setIsLanguageModalOpen] = useState(false);

  useEffect(() => {
    if (typeof window === "undefined") return;
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY) as LanguageCode;
      if (saved && TRANSLATIONS[saved]) {
        setLangState(saved);
      }
      const alreadyChosen = window.localStorage.getItem(FIRST_TIME_KEY);
      if (!alreadyChosen) {
        setIsLanguageModalOpen(true);
      }
    } catch {
      /* ignore */
    }
  }, []);

  const setLanguage = (newLang: LanguageCode) => {
    if (TRANSLATIONS[newLang]) {
      setLangState(newLang);
      if (typeof window !== "undefined") {
        window.localStorage.setItem(STORAGE_KEY, newLang);
        window.localStorage.setItem(FIRST_TIME_KEY, "true");
      }
    }
  };

  const openLanguageModal = () => setIsLanguageModalOpen(true);
  const closeLanguageModal = () => {
    if (typeof window !== "undefined") {
      window.localStorage.setItem(FIRST_TIME_KEY, "true");
    }
    setIsLanguageModalOpen(false);
  };

  const t = useMemo(() => {
    return (key: string, fallback?: string): string => {
      if (language === "en") {
        if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
        return fallback || key;
      }
      const dict = TRANSLATIONS[language];
      if (dict && dict[key]) return dict[key];
      if (fallback && dict && dict[fallback]) return dict[fallback];
      if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
      return fallback || key;
    };
  }, [language]);

  useEffect(() => {
    if (typeof window === "undefined" || !document.body) return;

    let isTranslating = false;

    const translateNode = (node: Node) => {
      if (node.nodeType === Node.TEXT_NODE) {
        const text = node.nodeValue || "";
        if (!text.trim()) return;

        if (!originalTextMap.has(node)) {
          originalTextMap.set(node, text);
        }
        const originalText = originalTextMap.get(node) || text;

        if (language === "en") {
          if (node.nodeValue !== originalText) {
            node.nodeValue = originalText;
          }
          return;
        }

        const translated = translateText(originalText, language);
        if (translated && translated !== node.nodeValue) {
          node.nodeValue = translated;
        }
      } else if (node.nodeType === Node.ELEMENT_NODE) {
        const el = node as HTMLElement;
        if (el.tagName === "SCRIPT" || el.tagName === "STYLE") return;

        const ph = el.getAttribute("placeholder");
        if (ph) {
          if (!el.hasAttribute("data-orig-ph")) {
            el.setAttribute("data-orig-ph", ph);
          }
          const origPh = el.getAttribute("data-orig-ph") || ph;
          if (language === "en") {
            el.setAttribute("placeholder", origPh);
          } else {
            const transPh = translateText(origPh, language);
            if (transPh && transPh !== ph) {
              el.setAttribute("placeholder", transPh);
            }
          }
        }

        const children = node.childNodes;
        for (let i = 0; i < children.length; i++) {
          translateNode(children[i]);
        }
      }
    };

    const runDOMTranslation = () => {
      if (isTranslating) return;
      isTranslating = true;
      try {
        translateNode(document.body);
      } finally {
        isTranslating = false;
      }
    };

    runDOMTranslation();

    const observer = new MutationObserver(() => {
      if (isTranslating) return;
      runDOMTranslation();
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });

    return () => {
      observer.disconnect();
    };
  }, [language]);

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        isLanguageModalOpen,
        openLanguageModal,
        closeLanguageModal,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
