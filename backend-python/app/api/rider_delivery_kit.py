"""Rider Delivery Kit API — Selection, Razorpay Payment & Zero-Bypass Verification.

Allows registering and active Captains to select their official Delivery Kit gear
(Waterproof Bag, T-Shirts, ID Card, Raincoat) with either Full Payment or Part Payment (Installments).
Enforces cryptographic Razorpay signature validation and provides status to unlock Agreement step.
"""

