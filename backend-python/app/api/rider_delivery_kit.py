@router.post("/create-order")
async def create_kit_razorpay_order(payload: CreateKitOrderPayload) -> Dict[str, Any]:
    """Generates server-side Razorpay Order for Full Payment or Part Payment Upfront."""
    clean_phone = "".join(c for c in payload.riderPhone if c.isdigit())
    if len(clean_phone) > 10:
        clean_phone = clean_phone[-10:]
    if len(clean_phone) != 10:
        raise HTTPException(status_code=400, detail="Invalid 10-digit mobile number")

    rules = await unified_finance_service.get_active_rules()
    kit_cfg = (rules.get("deliveryKit") or {}).get("standardKit") or {}

    is_part_payment = payload.paymentType.upper() in ("PART_PAYMENT", "PART", "INSTALLMENT")

    if is_part_payment:
        charge_amount = float(kit_cfg.get("partPaymentUpfront") or 300.0)
        total_price = float(kit_cfg.get("partPaymentTotalPrice") or 1200.0)
        remaining_balance = round(total_price - charge_amount, 2)
    else:
        charge_amount = float(kit_cfg.get("totalPrice") or 999.0)
        total_price = charge_amount
        remaining_balance = 0.0

    receipt_id = f"kit_{clean_phone}_{uuid.uuid4().hex[:6]}"

    notes = {
        "purpose": "QUICKPRESS_CAPTAIN_DELIVERY_KIT",
        "riderPhone": clean_phone,
        "riderName": payload.riderName or "Captain",
        "paymentType": "PART_PAYMENT" if is_part_payment else "FULL_PAYMENT",
        "tshirtSize": payload.tshirtSize,
        "totalKitPrice": total_price,
        "upfrontCharged": charge_amount,
        "remainingBalance": remaining_balance,
        "city": payload.city or "Kasganj",
    }

    try:
        rzp_order = await razorpay_client.create_order(
            amount=charge_amount,
            currency="INR",
            receipt=receipt_id,
            notes=notes,
        )
    except Exception as exc:
        logger.error("Failed to generate Razorpay order for rider delivery kit: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Payment gateway order creation failed: {exc}",
        )

    pg_cfg = razorpay_client.get_pg_config()

    return {
        "ok": True,
        "razorpayOrderId": rzp_order["id"],
        "amount": charge_amount,
        "currency": "INR",
        "keyId": pg_cfg.get("key_id", ""),
        "paymentType": "PART_PAYMENT" if is_part_payment else "FULL_PAYMENT",
        "totalPrice": total_price,
        "remainingBalance": remaining_balance,
        "notes": notes,
    }


@router.post("/verify-payment")
async def verify_kit_payment(payload: VerifyKitPaymentPayload) -> Dict[str, Any]:
    """Cryptographically verifies Razorpay signature and records verified kit order in database."""
    clean_phone = "".join(c for c in payload.riderPhone if c.isdigit())
    if len(clean_phone) > 10:
        clean_phone = clean_phone[-10:]
    if len(clean_phone) != 10:
        raise HTTPException(status_code=400, detail="Invalid 10-digit mobile number")

    # Idempotency lock to protect against rapid double-clicks
    idemp_key = f"{clean_phone}:{payload.razorpayPaymentId}"
    idemp = await idempotency_engine.acquire_or_wait("rider_kit_payment", idemp_key)
    if idemp.is_duplicate:
        if idemp.cached_data:
            return idemp.cached_data
        if idemp.is_processing:
            raise HTTPException(status_code=409, detail="Payment verification is already processing. Please wait.")

    # 1. Cryptographic HMAC-SHA256 signature check
    is_valid_sig = razorpay_client.verify_payment_signature(
        order_id=payload.razorpayOrderId,
        payment_id=payload.razorpayPaymentId,
        signature=payload.razorpaySignature,
    )
    if not is_valid_sig:
        await idempotency_engine.release("rider_kit_payment", idemp_key)
        raise HTTPException(status_code=400, detail="Invalid payment signature. Verification rejected.")

    # 2. Compute authoritative financial state
    rules = await unified_finance_service.get_active_rules()
    kit_cfg = (rules.get("deliveryKit") or {}).get("standardKit") or {}

    is_part_payment = payload.paymentType.upper() in ("PART_PAYMENT", "PART", "INSTALLMENT")

    if is_part_payment:
        paid_amount = float(kit_cfg.get("partPaymentUpfront") or 300.0)
        total_price = float(kit_cfg.get("partPaymentTotalPrice") or 1200.0)
        remaining_balance = round(total_price - paid_amount, 2)
        weekly_deduction = float(kit_cfg.get("deductionWeekly") or 300.0)
        status_val = "PARTIALLY_PAID"
    else:
        paid_amount = float(kit_cfg.get("totalPrice") or 999.0)
        total_price = paid_amount
        remaining_balance = 0.0
        weekly_deduction = 0.0
        status_val = "PAID"

    now_str = _now_iso()
    kit_order_id = f"kit-ord-{clean_phone}-{uuid.uuid4().hex[:6]}"

    kit_doc: Dict[str, Any] = {
        "_id": kit_order_id,
        "id": kit_order_id,
        "riderPhone": clean_phone,
        "riderName": payload.riderName or "Captain",
        "riderId": payload.riderId or f"rdr-{clean_phone}",
        "city": payload.city or "Kasganj",
        "kitId": payload.kitId or "kit_standard",
        "kitName": kit_cfg.get("name", "Standard Captain Starter Kit"),
        "tshirtSize": payload.tshirtSize or "L",
        "deliveryPreference": payload.deliveryPreference or "home_delivery",
        "shippingAddress": payload.shippingAddress or {},
        "pricing": {
            "totalKitPrice": total_price,
            "paymentType": "PART_PAYMENT" if is_part_payment else "FULL_PAYMENT",
            "amountPaid": paid_amount,
            "remainingBalance": remaining_balance,
            "upfrontPaid": paid_amount,
            "installmentWeeklyDeduction": weekly_deduction,
            "installmentsRecovered": 0.0,
            "fullySettled": not is_part_payment,
        },
        "payment": {
            "gateway": "razorpay",
            "status": status_val,
            "razorpayOrderId": payload.razorpayOrderId,
            "razorpayPaymentId": payload.razorpayPaymentId,
            "razorpaySignature": payload.razorpaySignature,
            "paidAt": now_str,
            "signatureVerified": True,
        },
        "fulfillment": {
            "status": "PENDING_DISPATCH",
            "courierName": "",
            "trackingNumber": "",
            "dispatchedAt": None,
            "deliveredAt": None,
            "deliveredBy": None,
            "notes": "",
        },
        "createdAt": now_str,
        "updatedAt": now_str,
    }

    # Upsert kit record in database
    await database.collection(DELIVERY_KITS_COLLECTION).update_one(
        {"riderPhone": clean_phone},
        {"$set": kit_doc},
        upsert=True,
    )

    # Link kit status to rider profile if profile exists
    rider_profile_updates = {
        "kitOrderId": kit_order_id,
        "kitPaymentStatus": status_val,
        "kitPaymentType": "PART_PAYMENT" if is_part_payment else "FULL_PAYMENT",
        "kitAmountPaid": paid_amount,
        "kitBalanceRemaining": remaining_balance,
        "kitTshirtSize": payload.tshirtSize,
        "kitDeliveryPreference": payload.deliveryPreference,
        "kitFulfillmentStatus": "PENDING_DISPATCH",
        "updatedAt": now_str,
    }
    await database.collection(RIDERS_COLLECTION).update_one(
        {"$or": [{"phone": clean_phone}, {"phoneNumber": clean_phone}, {"_id": payload.riderId or clean_phone}]},
        {"$set": rider_profile_updates},
    )

    response_data = {
        "ok": True,
        "status": status_val,
        "kitOrderId": kit_order_id,
        "paymentType": "PART_PAYMENT" if is_part_payment else "FULL_PAYMENT",
        "amountPaid": paid_amount,
        "remainingBalance": remaining_balance,
        "message": "Delivery kit payment successfully verified! Partner agreement is now unlocked.",
        "kitOrder": kit_doc,
    }

    await idempotency_engine.complete("rider_kit_payment", idemp_key, response_data)
    return response_data


@router.get("/my-kit")
async def get_my_kit_status(phone: str = Query(..., description="Rider 10-digit mobile number")) -> Dict[str, Any]:
    """Retrieves delivery kit order, dispatch status, tracking info, and installment recovery progress."""
    clean_phone = "".join(c for c in phone if c.isdigit())
    if len(clean_phone) > 10:
        clean_phone = clean_phone[-10:]

    kit = await database.find_one(DELIVERY_KITS_COLLECTION, {"riderPhone": clean_phone})
    if not kit:
        return {
            "ok": True,
            "hasKitOrder": False,
            "status": "UNPAID",
            "message": "No delivery kit order found for this rider.",
        }

    return {
        "ok": True,
        "hasKitOrder": True,
        "kitOrder": kit,
    }
